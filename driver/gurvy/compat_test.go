func TestCompatHashToG1GenericBESwu(t *testing.T) {
	// Known-answer check
	for idx, v := range hashToG1Vectors {
		wantRaw, err := hex.DecodeString(v.pointHex)
		require.NoError(t, err)

		gPoint, err := HashToG1GenericBESwu([]byte(v.msg), []byte(v.domain), sha256.New)
		require.NoError(t, err)

		gotRaw := gPoint.RawBytes()
		assert.Equal(t, wantRaw, gotRaw[:], "point mismatch at vector %d", idx)
	}

	// Property: random inputs produce valid BLS12-381 G1 points
	for i := range 50 {
		msg := []byte(string(rune(i)) + "prop_test_msg")
		domain := []byte("prop_test_domain")

		gPoint, err := HashToG1GenericBESwu(msg, domain, sha256.New)
		require.NoError(t, err)

		assert.True(t, gPoint.IsOnCurve(), "output not on curve at i=%d", i)
		assert.True(t, gPoint.IsInSubGroup(), "output not in subgroup at i=%d", i)
	}

	// Zero-value check: the point must not be the identity (infinity)
	gPoint, err := HashToG1GenericBESwu([]byte("non-empty"), []byte("domain"), sha256.New)
	require.NoError(t, err)
	var infinity bls12381.G1Affine
	assert.False(t, gPoint.Equal(&infinity), "hash-to-curve must not return the identity")
}
