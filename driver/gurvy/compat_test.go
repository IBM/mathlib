// ---------------------------------------------------------------------------
// TestCompatIsQuadraticResidue
// Property test: IsQuadraticResidue agrees with gnark-crypto fp.Sqrt.
// A value x is a residue iff Sqrt(x)² == x (and Sqrt is non-zero).
// Additionally, x² is always a residue.
// ---------------------------------------------------------------------------

func TestCompatIsQuadraticResidue(t *testing.T) {
	for i := range 1000 {
		var x fp.Element
		_, err := x.SetRandom()
		require.NoError(t, err)

		// x² is always a quadratic residue
		var x2 fp.Element
		x2.Square(&x)
		assert.Equal(t, uint64(1), IsQuadraticResidue(&x2), "x² must always be a residue")

		// For a random x, compare our result with gnark's Sqrt
		var s fp.Element
		s.Sqrt(&x)
		var s2 fp.Element
		s2.Square(&s)
		gnarkResidue := s2.Equal(&x) // gnark sqrt: s²==x iff x is a residue (or zero)
		if !x.IsZero() {
			gurvyResidue := IsQuadraticResidue(&x)
			if gnarkResidue {
				assert.Equal(t, uint64(1), gurvyResidue, "gnark says residue; gurvy must agree (i=%d)", i)
			} else {
				assert.Equal(t, uint64(0), gurvyResidue, "gnark says non-residue; gurvy must agree (i=%d)", i)
			}
		}
	}
}

// ---------------------------------------------------------------------------
// TestCompatSqrt
// Property test: Sqrt(x²)² == x²  (result is correct square root).
// ---------------------------------------------------------------------------

func TestCompatSqrt(t *testing.T) {
	for i := range 1000 {
		var x fp.Element
		_, err := x.SetRandom()
		require.NoError(t, err)

		var x2 fp.Element
		x2.Square(&x)

		var gSqrt fp.Element
		Sqrt(&gSqrt, &x2)

		// gSqrt² must equal x²
		var check fp.Element
		check.Square(&gSqrt)
		assert.True(t, check.Equal(&x2), "Sqrt(x²)² must equal x² (i=%d)", i)
	}
}

// ---------------------------------------------------------------------------
// TestCompatSgn0
// Property test: Sgn0(x) == 1 iff x (in canonical form) ≤ (p-1)/2.
// The comparison is done using big.Int arithmetic.
// ---------------------------------------------------------------------------

var pMinus1Over2BigInt *big.Int

func init() {
	// p = 0x1a0111ea397fe69a4b1ba7b6434bacd764774b84f38512bf6730d2a0f6b0f6241eabfffeb153ffffb9feffffffffaaab
	p, _ := new(big.Int).SetString(
		"4002409555221667393417789825735904156556882819939007885332058136124031650490837864442687629129015664037894272559787",
		10,
	)
	pMinus1Over2BigInt = new(big.Int).Rsh(new(big.Int).Sub(p, big.NewInt(1)), 1)
}

func TestCompatSgn0(t *testing.T) {
	for i := range 1000 {
		var x fp.Element
		_, err := x.SetRandom()
		require.NoError(t, err)

		// Canonical (non-Montgomery) representation as big.Int
		bits := x.Bits() // little-endian limbs, canonical form
		xBig := new(big.Int)
		for j := 5; j >= 0; j-- {
			xBig.Lsh(xBig, 64)
			xBig.Or(xBig, new(big.Int).SetUint64(bits[j]))
		}

		expectedSign := uint64(1) // 1 if x ≤ (p-1)/2
		if xBig.Cmp(pMinus1Over2BigInt) > 0 {
			expectedSign = 0
		}

		assert.Equal(t, expectedSign, Sgn0(&x), "Sgn0 mismatch at i=%d", i)
	}
}

