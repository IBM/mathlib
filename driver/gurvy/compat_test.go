func mustDecodeHex48(t *testing.T, s string) [48]byte {
	t.Helper()
	b, err := hex.DecodeString(s)
	require.NoError(t, err)
	require.Len(t, b, 48)
	var out [48]byte
	copy(out[:], b)

	return out
}

func mustFpFromHex(t *testing.T, s string) fp.Element {
	t.Helper()
	raw := mustDecodeHex48(t, s)
	var e fp.Element
	e.SetBytes(raw[:])

	return e
}

func TestCompatSwuMapG1BE(t *testing.T) {
	for idx, v := range swuMapG1BEVectors {
		u := mustFpFromHex(t, v.uHex)
		wantX := mustDecodeHex48(t, v.xHex)
		wantY := mustDecodeHex48(t, v.yHex)

		gotX, gotY := SwuMapG1BE(&u)
		assert.Equal(t, wantX, gotX.Bytes(), "X mismatch at vector %d", idx)
		assert.Equal(t, wantY, gotY.Bytes(), "Y mismatch at vector %d", idx)
	}

	// Property: random inputs produce points on E' (y² == x³ + a·x + b)
	for i := range 200 {
		var u fp.Element
		_, err := u.SetRandom()
		require.NoError(t, err)

		gX, gY := SwuMapG1BE(&u)

		// Verify y² == x³ + swuA·x + swuB
		var lhs, rhs, tmp fp.Element
		lhs.Square(gY) // y²
		rhs.Square(gX)
		rhs.Add(&rhs, &swuA)
		rhs.Mul(&rhs, gX)
		tmp.Set(&swuB)
		rhs.Add(&rhs, &tmp)
		assert.True(t, lhs.Equal(&rhs), "SwuMapG1BE output not on E' at i=%d", i)
	}
}

